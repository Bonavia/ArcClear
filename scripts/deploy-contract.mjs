import fs from 'node:fs';
import { createPublicClient, createWalletClient, defineChain, http } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
const network = process.argv.includes('--mainnet') ? 'mainnet' : 'testnet';
const key = process.env.DEPLOYER_PRIVATE_KEY;
if (!key || !/^0x[\da-fA-F]{64}$/.test(key)) throw new Error('Set DEPLOYER_PRIVATE_KEY in the environment. Never commit it.');
if (network === 'mainnet' && process.env.CONFIRM_MAINNET !== 'YES') throw new Error('Set CONFIRM_MAINNET=YES to deploy with real USDC gas.');
const chain = defineChain({ id: network === 'mainnet' ? 5042 : 5042002, name: `Arc ${network}`, nativeCurrency: { name: 'USDC', symbol: 'USDC', decimals: 18 }, rpcUrls: { default: { http: [`https://rpc.${network}.arc.io`] } } });
const account = privateKeyToAccount(key);
const wallet = createWalletClient({ account, chain, transport: http() });
const client = createPublicClient({ chain, transport: http() });
const artifact = JSON.parse(fs.readFileSync('contracts/artifacts/ArcClear.json', 'utf8'));
const fees = await client.estimateFeesPerGas();
const hash = await wallet.deployContract({ ...artifact, args: [], maxFeePerGas: fees.maxFeePerGas < 20_000_000_000n ? 20_000_000_000n : fees.maxFeePerGas, maxPriorityFeePerGas: fees.maxPriorityFeePerGas });
const receipt = await client.waitForTransactionReceipt({ hash });
if (receipt.status !== 'success' || !receipt.contractAddress) throw new Error('Deployment failed.');
fs.mkdirSync('deployments', { recursive: true });
fs.writeFileSync(`deployments/${network}.json`, JSON.stringify({ network, chainId: chain.id, address: receipt.contractAddress, transactionHash: hash }, null, 2) + '\n');
console.log(`ArcClear deployed: ${receipt.contractAddress}\nTransaction: ${hash}\nEnter this contract address in the app’s Arc settings.`);
